from __future__ import annotations

import sys
from collections.abc import Coroutine, Mapping
from contextlib import AbstractContextManager
from dataclasses import dataclass
from pathlib import Path
from typing import Any, BinaryIO, Protocol

from .config import AgentConfig
from .credentials import CredentialStore


class FilesystemAdapter(Protocol):
    def resolve_directory(self, path: str) -> dict: ...
    def stat(self, path: str) -> dict: ...
    def list(self, path: str, offset: int, limit: int) -> dict: ...
    def read(self, path: str, offset: int, limit: int, max_line_length: int) -> dict: ...
    def write(self, path: str, content: str, expected_sha256: str | None) -> dict: ...
    def upsert(self, path: str, content: str) -> dict: ...
    def edit(
        self,
        path: str,
        old_text: str,
        new_text: str,
        replace_all: bool,
        expected_sha256: str | None,
    ) -> dict: ...
    def patch(self, patch: str, expected_sha256: dict[str, str]) -> dict: ...
    def mkdir(self, path: str, parents: bool) -> dict: ...
    def copy_or_move(self, path: str, destination: str, *, move: bool) -> dict: ...
    def rename(self, path: str, destination: str) -> dict: ...
    def delete(self, path: str, recursive: bool) -> dict: ...
    def import_file(
        self, path: str, source: Path, overwrite: bool, expected_size: int, expected_sha256: str
    ) -> dict: ...
    def open_export(self, path: str) -> AbstractContextManager[tuple[BinaryIO, int, str]]: ...


class CacheAdapter(Protocol):
    async def ensure(self, artifact, transfer, client) -> dict: ...
    def store(self, artifact, source: BinaryIO) -> dict: ...
    def open_export(self, artifact) -> AbstractContextManager[tuple[BinaryIO, int, str]]: ...
    def evict(self) -> int: ...
    def clear(self) -> int: ...


class ProcessAdapter(Protocol):
    def inspect_shell(self, command: str, current_directory: str) -> dict: ...
    async def exec(self, **kwargs) -> dict: ...


class TerminalAdapter(Protocol):
    async def open(self, rows: int, columns: int, *, terminal_id: str | None = None) -> dict: ...
    async def read(self, terminal_id: str, max_bytes: int, wait_seconds: float) -> dict: ...
    async def write(self, terminal_id: str, data: str) -> dict: ...
    async def resize(self, terminal_id: str, rows: int, columns: int) -> dict: ...
    async def close(self, terminal_id: str) -> dict: ...
    async def run(self, **kwargs) -> dict: ...
    async def close_all(self) -> None: ...


class SearchAdapter(Protocol):
    async def glob(self, path: str, pattern: str) -> dict: ...
    async def grep(self, path: str, pattern: str, include: str | None) -> dict: ...


class BrowserAdapter(Protocol):
    async def dispatch(self, operation: str, arguments) -> dict: ...
    async def close(self) -> None: ...


class OpenScadAdapter(Protocol):
    def discover(self) -> dict: ...
    async def test(self, executable_path: str) -> dict: ...
    async def render(self, arguments, backend_id: str, *, six_views: bool) -> dict: ...


class TransferAdapter(Protocol):
    async def __aenter__(self): ...
    async def __aexit__(self, *args: object) -> None: ...
    def set_access_key(self, access_key: str) -> None: ...
    async def download(self, *args, **kwargs) -> Path: ...
    async def upload(self, *args, **kwargs) -> None: ...


@dataclass(frozen=True)
class RuntimeServices:
    platform: PlatformAdapter
    filesystem: FilesystemAdapter
    cache: CacheAdapter
    process: ProcessAdapter
    terminal: TerminalAdapter
    search: SearchAdapter
    browser: BrowserAdapter
    openscad: OpenScadAdapter
    transfer: TransferAdapter
    operations: tuple[str, ...]


class PlatformAdapter(Protocol):
    @property
    def platform_id(self) -> str: ...
    def computer_name(self) -> str: ...
    def default_config_path(self, environ: Mapping[str, str]) -> Path: ...
    def system_info(self, current_directory: str | None, filesystem: FilesystemAdapter) -> dict: ...
    def credential_store(self, data_dir: Path) -> CredentialStore: ...
    def build_runtime(
        self, config: AgentConfig, access_key: str, *, transfer_client=None
    ) -> RuntimeServices: ...
    def clear_cache(self, config: AgentConfig) -> int: ...
    def maintenance_running(self, config: AgentConfig) -> bool: ...
    async def start_maintenance(
        self,
        config: AgentConfig,
        action: str,
        job_id: str,
        password: str | None,
        revision: str | None = None,
    ) -> dict: ...
    def run_auxiliary(self, command: str, arguments: list[str]) -> bool: ...
    def run(self, coroutine: Coroutine[Any, Any, None]) -> None: ...


def current_platform() -> PlatformAdapter:
    if sys.platform.startswith("linux"):
        from .platform_linux import LinuxPlatform

        return LinuxPlatform()
    if sys.platform == "win32":
        from .platform_windows import WindowsPlatform

        return WindowsPlatform()
    raise RuntimeError(f"MatoLoop Agent does not support {sys.platform}")
